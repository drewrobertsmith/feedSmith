"""Draws the state gallery's fixture images and writes them as data URIs, so worlds load nothing over the network (FEE-70).

Usage: uvx --with pillow==11.3.0 python -I scripts/draw-fixture-images.py src/worlds/fixture-images.ts
"""
import base64
import io
import sys
from PIL import Image, ImageDraw

OUT = sys.argv[1]
SS = 4  # supersampling


def icon(background, draw_mark):
    s = 64 * SS
    img = Image.new('RGB', (s, s), background)
    draw_mark(ImageDraw.Draw(img), s)
    return img.resize((64, 64), Image.LANCZOS)


def verge(d, s):
    d.polygon([(s * .2, s * .25), (s * .38, s * .25), (s * .5, s * .62), (s * .62, s * .25), (s * .8, s * .25), (s * .5, s * .8)], fill=(255, 255, 255))


def fireball(d, s):
    d.ellipse([s * .22, s * .22, s * .78, s * .78], fill=(214, 160, 58))
    d.ellipse([s * .38, s * .38, s * .62, s * .62], fill=(40, 40, 40))


def farnam(d, s):
    for i, w in enumerate((.6, .45, .3)):
        y = s * (.28 + i * .17)
        d.rectangle([s * .2, y, s * (.2 + w), y + s * .09], fill=(30, 30, 30))


def gradient(w, h, top, bottom):
    img = Image.new('RGB', (w, h))
    d = ImageDraw.Draw(img)
    for y in range(h):
        t = y / (h - 1)
        d.line([(0, y), (w, y)], fill=tuple(round(a + (b - a) * t) for a, b in zip(top, bottom)))
    return img


def runway():
    img = gradient(480, 320, (120, 150, 175), (205, 210, 205))
    d = ImageDraw.Draw(img)
    d.rectangle([0, 210, 480, 320], fill=(85, 88, 84))
    d.polygon([(200, 320), (230, 210), (250, 210), (280, 320)], fill=(150, 150, 140))
    d.polygon([(150, 175), (330, 175), (300, 190), (180, 190)], fill=(45, 50, 55))
    d.polygon([(225, 150), (255, 150), (250, 200), (230, 200)], fill=(45, 50, 55))
    return img


def frame():
    img = gradient(480, 320, (226, 205, 178), (176, 140, 108))
    d = ImageDraw.Draw(img)
    d.rectangle([150, 70, 330, 220], fill=(35, 33, 32))
    d.rectangle([162, 82, 318, 208], fill=(110, 150, 170))
    d.rectangle([0, 250, 480, 320], fill=(120, 86, 60))
    return img


def uri(img, kind):
    buffer = io.BytesIO()
    if kind == 'png':
        img.save(buffer, 'PNG', optimize=True)
    else:
        img.save(buffer, 'JPEG', quality=70, optimize=True)
    return f'data:image/{kind};base64,' + base64.b64encode(buffer.getvalue()).decode()


IMAGES = {
    'VERGE_ICON': uri(icon((92, 44, 168), verge), 'png'),
    'FIREBALL_ICON': uri(icon((34, 34, 34), fireball), 'png'),
    'FARNAM_ICON': uri(icon((245, 242, 235), farnam), 'png'),
    'RUNWAY_PHOTO': uri(runway(), 'jpeg'),
    'FRAME_PHOTO': uri(frame(), 'jpeg'),
}

with open(OUT, 'w') as f:
    f.write('// Generated by scripts/draw-fixture-images.py; don\'t edit by hand.\n')
    f.write('// Local images for the worlds, so the gallery loads nothing over the network and two visual checks in a row match (FEE-70).\n\n')
    for name, value in IMAGES.items():
        f.write(f"export const {name} = '{value}';\n")
